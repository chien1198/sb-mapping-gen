           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_QUY_DOI_CLOS END), 0) AS QUY_DOI_CLOS_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_QUY_DOI_CLOS END), 0) AS QUY_DOI_CLOS_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_QUY_DOI_CLOS END), 0) AS QUY_DOI_CLOS_YTD,
           (SELECT COUNT(*) FROM PDTD_DTM.AGG_LOS_KPI_USER_YEAR u WHERE u.KPI_YEAR = EXTRACT(YEAR FROM p.v_batch_date)
            AND u.FIRST_ELIGIBLE_TS >= TRUNC(p.v_batch_date, 'IW') AND u.FIRST_ELIGIBLE_TS < p.v_batch_date + 1) AS USER_CNT_WTD,
           (SELECT COUNT(*) FROM PDTD_DTM.AGG_LOS_KPI_USER_YEAR u WHERE u.KPI_YEAR = EXTRACT(YEAR FROM p.v_batch_date)
            AND u.FIRST_ELIGIBLE_TS >= TRUNC(p.v_batch_date, 'MM') AND u.FIRST_ELIGIBLE_TS < p.v_batch_date + 1) AS USER_CNT_MTD,
           (SELECT COUNT(*) FROM PDTD_DTM.AGG_LOS_KPI_USER_YEAR u WHERE u.KPI_YEAR = EXTRACT(YEAR FROM p.v_batch_date)
            AND u.FIRST_ELIGIBLE_TS >= TRUNC(p.v_batch_date, 'Q') AND u.FIRST_ELIGIBLE_TS < p.v_batch_date + 1) AS USER_CNT_QTD,
           (SELECT COUNT(*) FROM PDTD_DTM.AGG_LOS_KPI_USER_YEAR u WHERE u.KPI_YEAR = EXTRACT(YEAR FROM p.v_batch_date)
            AND u.FIRST_ELIGIBLE_TS >= TRUNC(p.v_batch_date, 'YYYY') AND u.FIRST_ELIGIBLE_TS < p.v_batch_date + 1) AS USER_CNT_YTD
    FROM   p
    LEFT   JOIN b ON 1 = 1
    GROUP  BY p.v_batch_date
) s
ON (t.DAYID = s.DAYID)
WHEN MATCHED THEN UPDATE SET
