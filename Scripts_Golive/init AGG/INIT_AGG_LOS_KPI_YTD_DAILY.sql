-- INIT_AGG_LOS_KPI_YTD_DAILY.sql - first-run D0 cho PDTD_DTM.AGG_LOS_KPI_YTD_DAILY
--
-- MUC DICH: o D0 khong co dong D-1 nen cac cot luy ke (WTD/MTD/QTD/YTD) cua job ban thuong chi bang gia tri trong ngay.
--   Script ghi de 52 cot luy ke cua dong D0 (13 chi tieu x 4 ky) bang tong tinh truc tiep tren snapshot D0
--   (AGG_LOS_KPI_APPLICATION.DAYID = D0). Gan truc tiep, KHONG cong D-1, KHONG cong gia tri ngay. Cac cot "trong ngay" khong bi dung toi (o D0 khong co snapshot D-1 nen cac cot nay chua toan bo ho so da duyet, moi nam).
--   13 chi tieu: SLHS_RLOS, SLGN_RLOS, SLHS_CLOS, SLGN_CLOS, TAT_RLOS_SEC/UNSEC (SUM_HOUR, CASE_CNT), TAT_CLOS (SUM_HOUR, CASE_CNT),
--   QUY_DOI_RLOS, QUY_DOI_CLOS, USER_CNT.
--   Truc ngay (review 2026-11-23): SLHS tinh theo PROCESSED_DATE (ngay phe duyet cuoi) trong khoang ky, moi ho so dem 1 lan/nam, dem ca Rejected (HAS_FINAL_APPROVAL_FLAG = 'Y', review 2026-11-25);
--   TAT/QUY_DOI tinh theo MIN_APP_EXITDATE (ngay phe duyet LAN DAU, ke ca Reject) trong khoang ky, QUY_DOI dung NVL ve PROCESSED_DATE cho ho so
--   Cancelled chua tung duyet; WTD/MTD/QTD cua TAT/QUY_DOI chia ky theo cot KPI_FIRST_DATE trong CTE b (cung ngay do).
--   SLGN tinh theo FIRST_DISBURSED_DATE (ngay giai ngan lan dau, khong rang buoc nam phe duyet) trong khoang ky.
--
-- THU TU CHAY TAI D0 (bat buoc):
--   1. AGG_LOS_KPI_APPLICATION (D0)  ->  2. INIT_AGG_LOS_KPI_APPLICATION_FIRST_DISBURSED_DATE.sql (dat FIRST_DISBURSED_DATE = MIN(VALUE_DATE))
--   3. AGG_LOS_KPI_USER_YEAR  ->  4. job AGG_LOS_KPI_YTD_DAILY ban thuong (D0)  ->  5. SCRIPT NAY  ->  truoc khi dung PREV va chay batch D1.
--
-- CACH CHAY (1 lan, ngay D0):
--   1. Sua DEFINE v_batch_date ben duoi thanh ngay D0 (YYYY-MM-DD). De nguyen gia tri mac dinh thi TO_DATE bao loi (co chu y).
--   2. MERGE phai bao "1 row merged"; 0 dong nghia la chua co dong D0.
--   3. Neu job AGG_LOS_KPI_YTD_DAILY ban thuong cua D0 bi chay lai thi PHAI chay lai script nay ngay sau do (chay lai se dat cac cot luy ke ve gia tri ngay).
--   4. Script chay lai nhieu lan van cho cung ket qua (ghi de gia tri tuyet doi, khong cong don).
--
-- DIEU KIEN: lay nguyen tu LLD lld/pdtd_dtm/PDTD_DTM_AGG_LOS_KPI_YTD_DAILY.csv, chi bo cac dieu kien ngay trong ngay
--   (DAYID = v_batch_date; dieu kien ngay trong ngay: SLHS so PROCESSED_DATE voi snapshot D-1, TAT/QUY_DOI so MIN_APP_EXITDATE voi snapshot D-1,
--   SLGN FIRST_DISBURSED_DATE = v_batch_date) va thay bang khoang ngay theo ky
--   (>= dau ky AND < D0 + 1; PROCESSED_DATE la timestamp). NVL(...,0) de khong ra NULL.
--   Khoa noi DIM_*_PRODUCT.DIMENSION_KEY = AGG.SUB_PRODUCT_SK giu NGUYEN theo LLD. Ve ON, them AGG.DATASOURCE cho tung ben
--   CLOS/RLOS (khong doi ket qua vi moi dieu kien da co DATASOURCE; tranh nhan ban do trung khoa so).
--   Client phai dung UTF-8 (cac dieu kien co chuoi tieng Viet: 'Phát hành', 'Phê duyệt tín dụng', ...).

DEFINE v_batch_date = 'YYYY-MM-DD'

MERGE INTO PDTD_DTM.AGG_LOS_KPI_YTD_DAILY t
USING (
    WITH p AS (
        SELECT TO_DATE('&v_batch_date', 'YYYY-MM-DD') AS v_batch_date FROM dual
    ),
    b AS (
        SELECT AGG_LOS_KPI_APPLICATION.PROCESSED_DATE AS PROCESSED_DATE,
               COALESCE(FCT_RLOS_APPLICATION.MIN_APP_EXITDATE, FCT_CLOS_APPLICATION.MIN_APP_EXITDATE, AGG_LOS_KPI_APPLICATION.PROCESSED_DATE) AS KPI_FIRST_DATE,
               AGG_LOS_KPI_APPLICATION.FIRST_DISBURSED_DATE AS FIRST_DISBURSED_DATE,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_RLOS_APPLICATION.HAS_FINAL_APPROVAL_FLAG = 'Y'
                  AND FCT_RLOS_APPLICATION.BUSINESS_FLOW IN ('BL','KHCN_HO')
                  AND DIM_LOS_COMPANY.COMPANY_CODE NOT IN ('VN0010401','VN0010101','VN0010002')
                  AND ((NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') <> 'Credit Card' AND DIM_RLOS_APPLICATION.PRODUCT_NAME NOT IN ('SeAHome-Fast','SeAHome-FastTSDB')) OR (NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') = 'Credit Card' AND DIM_RLOS_APPLICATION.PRODUCT_NAME IN ('SeAHome-Fast','SeAHome-FastTSDB')))
                  AND AGG_LOS_KPI_APPLICATION.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') AND AGG_LOS_KPI_APPLICATION.PROCESSED_DATE < p.v_batch_date + 1
                    THEN 1 END AS C_SLHS_RLOS,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_RLOS_APPLICATION.APPLICATION_STATUS = 'Approved'
                  AND FCT_RLOS_APPLICATION.BUSINESS_FLOW IN ('BL','KHCN_HO')
                  AND DIM_LOS_COMPANY.COMPANY_CODE NOT IN ('VN0010401','VN0010101','VN0010002')
                  AND ((NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') <> 'Credit Card' AND DIM_RLOS_APPLICATION.PRODUCT_NAME NOT IN ('SeAHome-Fast','SeAHome-FastTSDB')) OR (NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') = 'Credit Card' AND DIM_RLOS_APPLICATION.PRODUCT_NAME IN ('SeAHome-Fast','SeAHome-FastTSDB')))
                  AND AGG_LOS_KPI_APPLICATION.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') AND AGG_LOS_KPI_APPLICATION.FIRST_DISBURSED_DATE < p.v_batch_date + 1
                    THEN 1 END AS C_SLGN_RLOS,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_CLOS_APPLICATION.HAS_FINAL_APPROVAL_FLAG = 'Y'
                  AND AGG_LOS_KPI_APPLICATION.APPLICATION_LINK_INFO IS NOT NULL
                  AND DIM_CLOS_APPLICATION.STREAM = 'Phê duyệt tín dụng'
                  AND (CASE WHEN AGG_LOS_KPI_APPLICATION.PRODUCTLINE_CODE = 'PRO02' AND DIM_CLOS_PRODUCT.SUB_PRODUCT_NAME = 'Phát hành LC theo món' THEN 0 ELSE 1 END) = 1
                  AND AGG_LOS_KPI_APPLICATION.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') AND AGG_LOS_KPI_APPLICATION.PROCESSED_DATE < p.v_batch_date + 1
                    THEN 1 END AS C_SLHS_CLOS,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_CLOS_APPLICATION.APPLICATION_STATUS = 'Approved'
                  AND AGG_LOS_KPI_APPLICATION.APPLICATION_LINK_INFO IS NOT NULL
                  AND DIM_CLOS_APPLICATION.STREAM = 'Phê duyệt tín dụng'
                  AND (CASE WHEN AGG_LOS_KPI_APPLICATION.PRODUCTLINE_CODE = 'PRO02' AND DIM_CLOS_PRODUCT.SUB_PRODUCT_NAME = 'Phát hành LC theo món' THEN 0 ELSE 1 END) = 1
                  AND AGG_LOS_KPI_APPLICATION.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') AND AGG_LOS_KPI_APPLICATION.FIRST_DISBURSED_DATE < p.v_batch_date + 1
                    THEN 1 END AS C_SLGN_CLOS,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_RLOS_APPLICATION.APPLICATION_STATUS IN ('Approved','Rejected')
                  AND FCT_RLOS_APPLICATION.BUSINESS_FLOW IN ('BL','KHCN_HO')
                  AND (CASE WHEN (NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') = 'Credit Card' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') OR DIM_RLOS_APPLICATION.PRODUCT_NAME IN ('SeABuyHuutri','SeACivil','SeAHome-Buy','SeAHome-Fast','SeAHome-Woman','SeAHome-Teacher','SeAFast_KTSBD_KD') OR (DIM_RLOS_APPLICATION.PRODUCT_NAME = 'SeAHome-Pro' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') THEN 1 ELSE 0 END) = 0
                  AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE >= TRUNC(p.v_batch_date, 'YYYY') AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE < p.v_batch_date + 1
                    THEN AGG_LOS_KPI_APPLICATION.TAT_APPLICATION_HOUR END AS C_TAT_RLOS_SEC_SUM_HOUR,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_RLOS_APPLICATION.APPLICATION_STATUS IN ('Approved','Rejected')
                  AND FCT_RLOS_APPLICATION.BUSINESS_FLOW IN ('BL','KHCN_HO')
                  AND (CASE WHEN (NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') = 'Credit Card' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') OR DIM_RLOS_APPLICATION.PRODUCT_NAME IN ('SeABuyHuutri','SeACivil','SeAHome-Buy','SeAHome-Fast','SeAHome-Woman','SeAHome-Teacher','SeAFast_KTSBD_KD') OR (DIM_RLOS_APPLICATION.PRODUCT_NAME = 'SeAHome-Pro' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') THEN 1 ELSE 0 END) = 0
                  AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE >= TRUNC(p.v_batch_date, 'YYYY') AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE < p.v_batch_date + 1
                    THEN 1 END AS C_TAT_RLOS_SEC_CASE_CNT,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_RLOS_APPLICATION.APPLICATION_STATUS IN ('Approved','Rejected')
                  AND FCT_RLOS_APPLICATION.BUSINESS_FLOW IN ('BL','KHCN_HO')
                  AND (CASE WHEN (NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') = 'Credit Card' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') OR DIM_RLOS_APPLICATION.PRODUCT_NAME IN ('SeABuyHuutri','SeACivil','SeAHome-Buy','SeAHome-Fast','SeAHome-Woman','SeAHome-Teacher','SeAFast_KTSBD_KD') OR (DIM_RLOS_APPLICATION.PRODUCT_NAME = 'SeAHome-Pro' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') THEN 1 ELSE 0 END) = 1
                  AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE >= TRUNC(p.v_batch_date, 'YYYY') AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE < p.v_batch_date + 1
                    THEN AGG_LOS_KPI_APPLICATION.TAT_APPLICATION_HOUR END AS C_TAT_RLOS_UNSEC_SUM_HOUR,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_RLOS_APPLICATION.APPLICATION_STATUS IN ('Approved','Rejected')
                  AND FCT_RLOS_APPLICATION.BUSINESS_FLOW IN ('BL','KHCN_HO')
                  AND (CASE WHEN (NVL(CASE WHEN DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%Phát hành%' OR DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME LIKE '%TTD%' THEN 'Credit Card' ELSE DIM_RLOS_PRODUCT.SUB_PRODUCT_NAME END, 'XX') = 'Credit Card' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') OR DIM_RLOS_APPLICATION.PRODUCT_NAME IN ('SeABuyHuutri','SeACivil','SeAHome-Buy','SeAHome-Fast','SeAHome-Woman','SeAHome-Teacher','SeAFast_KTSBD_KD') OR (DIM_RLOS_APPLICATION.PRODUCT_NAME = 'SeAHome-Pro' AND DIM_RLOS_APPLICATION.COLL_REQUIRE = 'NO') THEN 1 ELSE 0 END) = 1
                  AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE >= TRUNC(p.v_batch_date, 'YYYY') AND FCT_RLOS_APPLICATION.MIN_APP_EXITDATE < p.v_batch_date + 1
                    THEN 1 END AS C_TAT_RLOS_UNSEC_CASE_CNT,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_CLOS_APPLICATION.APPLICATION_STATUS IN ('Approved','Rejected')
                  AND DIM_CLOS_APPLICATION.STREAM = 'Phê duyệt tín dụng'
                  AND FCT_CLOS_APPLICATION.MIN_APP_EXITDATE >= TRUNC(p.v_batch_date, 'YYYY') AND FCT_CLOS_APPLICATION.MIN_APP_EXITDATE < p.v_batch_date + 1
                    THEN AGG_LOS_KPI_APPLICATION.TAT_APPLICATION_HOUR END AS C_TAT_CLOS_SUM_HOUR,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND FCT_CLOS_APPLICATION.APPLICATION_STATUS IN ('Approved','Rejected')
                  AND DIM_CLOS_APPLICATION.STREAM = 'Phê duyệt tín dụng'
                  AND FCT_CLOS_APPLICATION.MIN_APP_EXITDATE >= TRUNC(p.v_batch_date, 'YYYY') AND FCT_CLOS_APPLICATION.MIN_APP_EXITDATE < p.v_batch_date + 1
                    THEN 1 END AS C_TAT_CLOS_CASE_CNT,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND NVL(FCT_RLOS_APPLICATION.MIN_APP_EXITDATE, AGG_LOS_KPI_APPLICATION.PROCESSED_DATE) >= TRUNC(p.v_batch_date, 'YYYY') AND NVL(FCT_RLOS_APPLICATION.MIN_APP_EXITDATE, AGG_LOS_KPI_APPLICATION.PROCESSED_DATE) < p.v_batch_date + 1
                    THEN AGG_LOS_KPI_APPLICATION.QUY_DOI END AS C_QUY_DOI_RLOS,
               CASE WHEN AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
                  AND AGG_LOS_KPI_APPLICATION.IS_TEST_ACCOUNT != 'Y'
                  AND NVL(FCT_CLOS_APPLICATION.MIN_APP_EXITDATE, AGG_LOS_KPI_APPLICATION.PROCESSED_DATE) >= TRUNC(p.v_batch_date, 'YYYY') AND NVL(FCT_CLOS_APPLICATION.MIN_APP_EXITDATE, AGG_LOS_KPI_APPLICATION.PROCESSED_DATE) < p.v_batch_date + 1
                    THEN AGG_LOS_KPI_APPLICATION.QUY_DOI END AS C_QUY_DOI_CLOS
        FROM   PDTD_DTM.AGG_LOS_KPI_APPLICATION AGG_LOS_KPI_APPLICATION
        CROSS  JOIN p
        LEFT JOIN PDTD_DTM.FCT_RLOS_APPLICATION FCT_RLOS_APPLICATION ON FCT_RLOS_APPLICATION.WI_NAME = AGG_LOS_KPI_APPLICATION.WI_NAME AND FCT_RLOS_APPLICATION.DAYID = AGG_LOS_KPI_APPLICATION.DAYID AND AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
        LEFT JOIN PDTD_DTM.DIM_LOS_COMPANY DIM_LOS_COMPANY ON DIM_LOS_COMPANY.DIMENSION_KEY = AGG_LOS_KPI_APPLICATION.COMPANY_SK AND AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
        LEFT JOIN PDTD_DTM.DIM_RLOS_PRODUCT DIM_RLOS_PRODUCT ON DIM_RLOS_PRODUCT.DIMENSION_KEY = AGG_LOS_KPI_APPLICATION.SUB_PRODUCT_SK AND AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
        LEFT JOIN PDTD_DTM.DIM_RLOS_APPLICATION DIM_RLOS_APPLICATION ON DIM_RLOS_APPLICATION.DIMENSION_KEY = AGG_LOS_KPI_APPLICATION.APPLICATION_SK AND AGG_LOS_KPI_APPLICATION.DATASOURCE = 'RLOS'
        LEFT JOIN PDTD_DTM.DIM_CLOS_APPLICATION DIM_CLOS_APPLICATION ON DIM_CLOS_APPLICATION.DIMENSION_KEY = AGG_LOS_KPI_APPLICATION.APPLICATION_SK AND AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
        LEFT JOIN PDTD_DTM.FCT_CLOS_APPLICATION FCT_CLOS_APPLICATION ON FCT_CLOS_APPLICATION.WI_NAME = AGG_LOS_KPI_APPLICATION.WI_NAME AND FCT_CLOS_APPLICATION.DAYID = AGG_LOS_KPI_APPLICATION.DAYID AND AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
        LEFT JOIN PDTD_DTM.DIM_CLOS_PRODUCT DIM_CLOS_PRODUCT ON DIM_CLOS_PRODUCT.DIMENSION_KEY = AGG_LOS_KPI_APPLICATION.SUB_PRODUCT_SK AND AGG_LOS_KPI_APPLICATION.DATASOURCE = 'CLOS'
        WHERE  AGG_LOS_KPI_APPLICATION.DAYID = p.v_batch_date
        AND   ((AGG_LOS_KPI_APPLICATION.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') AND AGG_LOS_KPI_APPLICATION.PROCESSED_DATE < p.v_batch_date + 1)
            OR (AGG_LOS_KPI_APPLICATION.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') AND AGG_LOS_KPI_APPLICATION.FIRST_DISBURSED_DATE < p.v_batch_date + 1))
    )
    SELECT p.v_batch_date AS DAYID,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_SLHS_RLOS END), 0) AS SLHS_RLOS_WTD,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_SLHS_RLOS END), 0) AS SLHS_RLOS_MTD,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_SLHS_RLOS END), 0) AS SLHS_RLOS_QTD,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_SLHS_RLOS END), 0) AS SLHS_RLOS_YTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_SLGN_RLOS END), 0) AS SLGN_RLOS_WTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_SLGN_RLOS END), 0) AS SLGN_RLOS_MTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_SLGN_RLOS END), 0) AS SLGN_RLOS_QTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_SLGN_RLOS END), 0) AS SLGN_RLOS_YTD,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_SLHS_CLOS END), 0) AS SLHS_CLOS_WTD,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_SLHS_CLOS END), 0) AS SLHS_CLOS_MTD,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_SLHS_CLOS END), 0) AS SLHS_CLOS_QTD,
           NVL(SUM(CASE WHEN b.PROCESSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_SLHS_CLOS END), 0) AS SLHS_CLOS_YTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_SLGN_CLOS END), 0) AS SLGN_CLOS_WTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_SLGN_CLOS END), 0) AS SLGN_CLOS_MTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_SLGN_CLOS END), 0) AS SLGN_CLOS_QTD,
           NVL(SUM(CASE WHEN b.FIRST_DISBURSED_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_SLGN_CLOS END), 0) AS SLGN_CLOS_YTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_TAT_RLOS_SEC_SUM_HOUR END), 0) AS TAT_RLOS_SEC_SUM_HOUR_WTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_TAT_RLOS_SEC_SUM_HOUR END), 0) AS TAT_RLOS_SEC_SUM_HOUR_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_TAT_RLOS_SEC_SUM_HOUR END), 0) AS TAT_RLOS_SEC_SUM_HOUR_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_TAT_RLOS_SEC_SUM_HOUR END), 0) AS TAT_RLOS_SEC_SUM_HOUR_YTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_TAT_RLOS_SEC_CASE_CNT END), 0) AS TAT_RLOS_SEC_CASE_CNT_WTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_TAT_RLOS_SEC_CASE_CNT END), 0) AS TAT_RLOS_SEC_CASE_CNT_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_TAT_RLOS_SEC_CASE_CNT END), 0) AS TAT_RLOS_SEC_CASE_CNT_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_TAT_RLOS_SEC_CASE_CNT END), 0) AS TAT_RLOS_SEC_CASE_CNT_YTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_TAT_RLOS_UNSEC_SUM_HOUR END), 0) AS TAT_RLOS_UNSEC_SUM_HOUR_WTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_TAT_RLOS_UNSEC_SUM_HOUR END), 0) AS TAT_RLOS_UNSEC_SUM_HOUR_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_TAT_RLOS_UNSEC_SUM_HOUR END), 0) AS TAT_RLOS_UNSEC_SUM_HOUR_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_TAT_RLOS_UNSEC_SUM_HOUR END), 0) AS TAT_RLOS_UNSEC_SUM_HOUR_YTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_TAT_RLOS_UNSEC_CASE_CNT END), 0) AS TAT_RLOS_UNSEC_CASE_CNT_WTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_TAT_RLOS_UNSEC_CASE_CNT END), 0) AS TAT_RLOS_UNSEC_CASE_CNT_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_TAT_RLOS_UNSEC_CASE_CNT END), 0) AS TAT_RLOS_UNSEC_CASE_CNT_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_TAT_RLOS_UNSEC_CASE_CNT END), 0) AS TAT_RLOS_UNSEC_CASE_CNT_YTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_TAT_CLOS_SUM_HOUR END), 0) AS TAT_CLOS_SUM_HOUR_WTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_TAT_CLOS_SUM_HOUR END), 0) AS TAT_CLOS_SUM_HOUR_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_TAT_CLOS_SUM_HOUR END), 0) AS TAT_CLOS_SUM_HOUR_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_TAT_CLOS_SUM_HOUR END), 0) AS TAT_CLOS_SUM_HOUR_YTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_TAT_CLOS_CASE_CNT END), 0) AS TAT_CLOS_CASE_CNT_WTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_TAT_CLOS_CASE_CNT END), 0) AS TAT_CLOS_CASE_CNT_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_TAT_CLOS_CASE_CNT END), 0) AS TAT_CLOS_CASE_CNT_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_TAT_CLOS_CASE_CNT END), 0) AS TAT_CLOS_CASE_CNT_YTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'IW') THEN b.C_QUY_DOI_RLOS END), 0) AS QUY_DOI_RLOS_WTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'MM') THEN b.C_QUY_DOI_RLOS END), 0) AS QUY_DOI_RLOS_MTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'Q') THEN b.C_QUY_DOI_RLOS END), 0) AS QUY_DOI_RLOS_QTD,
           NVL(SUM(CASE WHEN b.KPI_FIRST_DATE >= TRUNC(p.v_batch_date, 'YYYY') THEN b.C_QUY_DOI_RLOS END), 0) AS QUY_DOI_RLOS_YTD,
