WITH SRC AS
(
    SELECT
      A.DAYID AS DAYID,
      A.CUSTOMER_CODE AS CUSTOMER_ID,
      D.SHORT_NAME AS SHORT_NAME,
      E.BRANCH_NAME AS BRANCH_NAME,
      E.COMPANY_NAME_VN AS COMPANY_NAME,
      G.REGION_NAME AS ZONE,                          
      A.CONTRACT AS CONTRACT,
      C.VALUE_DATE AS VALUE_DATE,
      C.MATURITY_DATE AS MATURITY_DATE,
      C.REC_STATUS AS STATUS,
      ABS(A.FIRST_DISBURSEMENT_AMT) AS DISBURSEMENT_AMT_T24,
      (ABS(NVL(A.BALANCE,0)) + ABS(NVL(A.PD_BALANCE,0))) * A.REVAL_RATE AS CUR_BALANCE,
      B.NO_DAYS_OVERDUE AS NO_DAYS_OVERDUE,
      CASE WHEN B.NO_DAYS_OVERDUE > 360 THEN 5
           WHEN B.NO_DAYS_OVERDUE > 180 THEN 4
           WHEN B.NO_DAYS_OVERDUE > 90  THEN 3
           WHEN B.NO_DAYS_OVERDUE >= 10 THEN 2
           ELSE 1 END AS CUR_BUCKET,
      F.SEAB_PRODUCTS_DE_NAME AS PRODUCT_T24,
      A.SEAB_LOS_ID AS SEAB_LOS_ID,
      APPR.APPROVAL_DATE AS APPROVAL_DATE,
      C.CONTRACT_REF AS CONTRACT_REF,
      C.REF_VALUE_DATE AS REF_VALUE_DATE
    FROM STG_DTM.STG_FCT_LOAN A
    INNER JOIN STG_DTM.STG_DIM_CUSTOMER D
      ON A.CUSTOMER_SK = D.DIMENSION_KEY
     AND D.SEAB_CU_SEGMENT IN ('14','21')
    LEFT JOIN STG_DTM.STG_DIM_LOAN C
      ON A.CONTRACT_SK = C.DIMENSION_KEY
    LEFT JOIN STG_DTM.STG_FCT_LOAN B
      ON A.PD_CONTRACT = B.CONTRACT
     AND B.DAYID = A.DAYID
    LEFT JOIN STG_DTM.STG_DIM_SEAB_PRODUCTS_DE F
      ON A.SEAB_PRODUCTS_DE_SK = F.DIMENSION_KEY
    LEFT JOIN STG_DTM.STG_DIM_COMPANY E
      ON A.CO_CODE = E.COMPANY_CODE
     AND E.COMPANY_EXP_DATE IS NULL
    LEFT JOIN TMP_REF_COMPANY_REGION G
      ON A.CO_CODE = G.COMPANY_CODE
    LEFT JOIN (
      SELECT H.WINAME, MAX(H.EXITDATE) AS APPROVAL_DATE
      FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT H
      WHERE H.WINAME IS NOT NULL
        AND H.WORKSTEP IS NOT NULL
        AND H.WORKSTEP IN ('CreditApprovalReview','CreditApproval','CreditCommittee')
        AND H.DECISION IN ('Submit','Send To HOSupport','Send To PostSanction','Submit To DisbursementMaker')
      GROUP BY H.WINAME
    ) APPR
      ON A.SEAB_LOS_ID = APPR.WINAME
    WHERE A.DAYID = TO_DATE(:DATE,'YYYYMMDD')
),
TBL AS
(
    SELECT
      DAYID, CUSTOMER_ID, SHORT_NAME, BRANCH_NAME, COMPANY_NAME, ZONE,
      CONTRACT, VALUE_DATE, MATURITY_DATE, STATUS, DISBURSEMENT_AMT_T24,
      CUR_BALANCE, NO_DAYS_OVERDUE, CUR_BUCKET, PRODUCT_T24, SEAB_LOS_ID,
      APPROVAL_DATE, CONTRACT_REF, REF_VALUE_DATE
    FROM PDTD_DTM.BC10
    WHERE DAYID = TO_DATE(:DATE,'YYYYMMDD')
)
SELECT * FROM SRC MINUS SELECT * FROM TBL
