WITH LOANCASEID_FINAL AS
(   SELECT H.WI_NAME,
        H.LOANCASEID AS RAW_LOANCASEID,
        CASE WHEN M.CHANGE_REQUEST = 'New' THEN H.loancaseid ELSE NULL END AS LOANCASEID
    FROM SBLOS2.NG_SB_CLOS_EXITABLE H
    LEFT JOIN SBLOS2.NG_SB_CLOS_CHANGEREQ M
        ON H.WI_NAME = M.WI_NAME AND M.CHANGE_REQUEST = 'New'
),
APPROVAL_WINAME_CALC AS
(
    SELECT H.WI_NAME,
        MIN(H.WI_NAME) OVER (PARTITION BY H.LOANCASEID) AS APPROVAL_WINAME_LOS
    FROM SBLOS2.NG_SB_CLOS_EXITABLE H
),
APPROVAL_DATE_CALC AS
(
    SELECT N.WINAME,
        MAX(N.EXITDATE) AS APPROVAL_DATE
    FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT N
    WHERE N.USERNAME IS NOT NULL
      AND N.WORKSTEP IN ('CreditApproval','CreditCommittee')
      AND N.DECISION IN ('Submit','Send To HOSupport','Send To PostSanction')
    GROUP BY N.WI_NAME
),
SRC AS
(
    SELECT
        A.SEAB_LOS_ID AS SEAB_LOS_ID,
        LC.LOANCASEID AS LOANCASEID,
        AW.APPROVAL_WINAME_LOS AS APPROVAL_WINAME_LOS,
        AD.APPROVAL_DATE AS APPROVAL_DATE
    FROM STG_DTM.STG_FCT_LOAN A
    INNER JOIN STG_DTM.STG_DIM_CUSTOMER_VW D ON A.CUSTOMER_SK = D.DIMENSION_KEY 
			AND D.SEAB_CU_SEGMENT NOT IN ('14','21')
    LEFT JOIN LOANCASEID_FINAL LC ON A.SEAB_LOS_ID = LC.WI_NAME
    LEFT JOIN APPROVAL_WINAME_CALC AW ON A.SEAB_LOS_ID = AW.WI_NAME
    LEFT JOIN APPROVAL_DATE_CALC AD ON A.SEAB_LOS_ID = AD.WI_NAME
    WHERE A.dayid = TO_DATE(:DATE,'YYYYMMDD')
),
TBL AS
(
    SELECT SEAB_LOS_ID, LOANCASEID, APPROVAL_WINAME_LOS, APPROVAL_DATE
    FROM PDTD_DTM.BC11
    WHERE DAYID = TO_DATE(:DATE,'YYYYMMDD')
)
SELECT 'SRC' AS SRC, x.* FROM (SELECT * FROM SRC MINUS SELECT * FROM TBL) x
UNION ALL
SELECT 'TBL' AS SRC, y.* FROM (SELECT * FROM TBL MINUS SELECT * FROM SRC) y;