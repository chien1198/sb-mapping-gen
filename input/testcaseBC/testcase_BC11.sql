WITH SRC AS (
SELECT
	A.DAYID AS DAYID,
	A.CUSTOMER_CODE AS CUSTOMER_ID,
	D.SHORT_NAME AS SHORT_NAME,
	I.CUST_GROUP AS CUST_GROUP,
	E.BRANCH_NAME AS BRANCH_NAME,
	E.COMPANY_NAME_VN AS COMPANY_NAME,
	G.REGION_NAME AS ZONE,
	A.CONTRACT AS CONTRACT,
	C.VALUE_DATE AS VALUE_DATE,
	C.MATURITY_DATE AS MATURITY_DATE,
	C.REC_STATUS AS STATUS,
	ABS(A.FIRST_DISBURSEMENT_AMT) AS DISBURSEMENT_AMT_T24,
	(ABS(NVL(A.BALANCE,0)) + ABS(NVL(A.PD_BALANCE, 0))) * A.REVAL_RATE AS CUR_BALANCE,
	B.NO_DAYS_OVERDUE AS NO_DAYS_OVERDUE,
	CASE WHEN B.NO_DAYS_OVERDUE > 360 THEN 5
		 WHEN B.NO_DAYS_OVERDUE > 180 THEN 4
		 WHEN B.NO_DAYS_OVERDUE > 90 THEN 3
		 WHEN B.NO_DAYS_OVERDUE >= 10 THEN 2
		ELSE 1 END AS CUR_BUCKET,
	F.SEAB_PRODUCTS_DE_NAME AS PRODUCT_T24,
	A.SEAB_LOS_ID AS SEAB_LOS_ID,
	C.CONTRACT_REF AS CONTRACT_REF,
	C.REF_VALUE_DATE AS REF_VALUE_DATE,
	A.LIMIT_REF AS LIMIT_REFERENCE
FROM STG_DTM.STG_FCT_LOAN A
INNER JOIN STG_DTM.STG_DIM_CUSTOMER_VW D ON A.CUSTOMER_SK = D.DIMENSION_KEY 
			AND D.SEAB_CU_SEGMENT NOT IN ('14', '21')
LEFT JOIN STG_DTM.STG_FCT_LOAN B ON A.PD.CONTRACT = B.CONTRACT AND B.DAYID = A.DAYID
LEFT JOIN STG_DTM.STG_DIM_LOAN C ON A.CONTRACT_SK = C.DIMENSION_KEY
LEFT JOIN STG_DTM.STG_DIM_COMPANY E ON A.CO_CODE = E.COMPANY_CODE AND E.COMPANY_EXP_DATE IS NULL
LEFT JOIN STG_DTM.STG_DIM_SEAB_PRODUCTS_DE F ON A.SEAB_PRODUCTS_SK = F.DIMENSION_KEY
LEFT JOIN TMP_REF_COMPANY_REGION G ON A.CO_CODE = G.COMPANY_CODE
LEFT JOIN SBLOS2.NG_SB_CLOS_EXITABLE H ON A.SEAB_LOS_ID = H.WI_NAME
LEFT JOIN SBLOS2.NG_SB_CLOS_CUST_INFO I ON A.SEAB_LOS_ID = I.WI_NAME
WHERE A.DAYID = TO_DATE(:DATE, 'YYYYMMDD')
),
TBL AS (
	SELECT DAYID, CUSTOMER_ID, SHORT_NAME, CUST_GROUP,
	BRANCH_NAME, COMPANY_NAME, ZONE, CONTRACT, VALUE_DATE, 
	MATURITY_DATE, STATUS, DISBURSEMENT_AMT_T24, CUR_BALANCE,
	NO_DAYS_OVERDUE, CUR_BUCKET, PRODUCT_T24, SEAB_LOS_ID,
	CONTRACT_REF, REF_VALUE_DATE, LIMIT_REFERENCE
	FROM PDTD_DTM.BC11
	WHERE DAYID = TO_DATE(:DATE, 'YYYYMMDD')
)
SELECT 'SRC' AS SRC, x.* FROM (SELECT * FROM SRC MINUS SELECT * FROM TBL) x
UNION ALL
SELECT 'TBL' AS SRC, y.* FROM (SELECT * FROM TBL MINUS SELECT * FROM SRC) y;

