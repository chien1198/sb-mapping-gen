WITH SRC AS
    (
    SELECT
        'CLOS' AS SYSTEMNAME,
        A.WINAME AS WINAME,
        B.STREAM AS STREAM,
        C.CUSTOMER_NAME AS CUSTOMER_NAME,
        A.WORKSTEP AS WORKSTEP,
        A.DECISION AS DECISION,
        CASE WHEN A.WORKSTEP = 'CreditApproval' THEN A.USERNAME END AS BI_APPROVER,
        CASE WHEN A.WORKSTEP = 'CreditCommittee' THEN A.USERNAME END AS BI_COMMITTEE,
        A.ENTRYDATE AS ENTRYDATE,
        A.EXITDATE AS EXITDATE,
        A.REMARKS AS REMARKS,
        E.CREDIT_LIMIT AS CREDIT_LIMIT,
        E.CURRENCY AS CURRENCY,
        E.CREDIT_TERM AS CREDIT_TERM,
        F.COLLTYPE AS TYPES_OF_COLLATERALS,
        F.APPRAISED_VAL_FIG AS APPRAISED_VALUE,
        F.DESCRIPTION AS DESCRIPTION,
        F.COLL_OWNER AS OWNER,
        F.LTV AS LTV,
        DBMS_LOB.SUBSTR(F.COLL_MGMT_APP, 4000, 1) AS COLLATERAL_MANAGEMENT
    FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT A
    LEFT JOIN SBLOS2.NG_SB_CLOS_APPROVAL B ON A.WINAME = B.WI_NAME
    LEFT JOIN SBLOS2.NG_SB_CLOS_CUST_INFO C ON A.WINAME = C.WI_NAME
    LEFT JOIN SBLOS2.NG_SB_CLOS_CREDITINFO_COMM E ON A.WINAME = E.WI_NAME
    LEFT JOIN SBLOS2.NG_SB_CLOS_COLL_CD F ON A.WINAME = F.WI_NAME
    WHERE A.WORKSTEP IN ('CreditApproval','CreditCommittee')
      AND A.DECISION IN ('Submit','Reject','Send to HOSupport','Send to PostSanction')
    UNION ALL
    SELECT
        'RLOS' AS SYSTEMNAME,
        A.WINAME AS WINAME,
        B.STREAM AS STREAM,
        C.FULL_NAME AS CUSTOMER_NAME,
        A.WORKSTEP AS WORKSTEP,
        A.DECISION AS DECISION,
        CASE WHEN A.WORKSTEP = 'CreditApproval' THEN A.USERNAME END AS BI_APPROVER,
        CASE WHEN A.WORKSTEP = 'CreditCommittee' THEN A.USERNAME END AS BI_COMMITTEE,
        A.ENTRYDATE AS ENTRYDATE,
        A.EXITDATE AS EXITDATE,
        A.REMARKS AS REMARKS,
        E.LOAN_AMOUNT AS CREDIT_LIMIT,
        E.LOAN_CURRENCY AS CURRENCY,
        E.LOAN_TERM AS CREDIT_TERM,
        COL.TYPE_COLL AS TYPES_OF_COLLATERALS,
        COL.APPRAISED_VALUE AS APPRAISED_VALUE,
        COL.DESC_COLL AS DESCRIPTION,
        COL.OWNER AS OWNER,
        COL.LOANRATE AS LTV,
        CAST(NULL AS VARCHAR2(4000)) AS COLLATERAL_MANAGEMENT
    FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT A
    LEFT JOIN SBLOS2.NG_SB_RLOS_APPROVAL B ON A.WINAME = B.WI_NAME
    LEFT JOIN SBLOS2.NG_SB_RLOS_APPLICANT_GENERAL C ON A.WINAME = C.WI_NAME
    LEFT JOIN SBLOS2.NG_SB_RLOS_CREDIT_PROPOSAL E ON A.WINAME = E.WI_NAME
    LEFT JOIN RLOS_COLLATERAL COL ON A.WINAME = COL.WI_NAME
    WHERE A.WORKSTEP IN ('CreditApproval','CreditCommittee')
      AND A.DECISION IN ('Submit','Reject','Send to HOSupport','Send to PostSanction')
    ),
    TBL AS
    (
    SELECT
        SYSTEMNAME, WINAME, STREAM, CUSTOMER_NAME, WORKSTEP, DECISION,
        BI_APPROVER, BI_COMMITTEE, ENTRYDATE, EXITDATE, REMARKS,
        CREDIT_LIMIT, CURRENCY, CREDIT_TERM,
        TYPES_OF_COLLATERALS, APPRAISED_VALUE, DESCRIPTION, OWNER, LTV
    FROM PDTD_DTM.BC3
    )
SELECT 'NGUON - DICH' AS SRC_FLAG, x.* FROM (SELECT * FROM SRC MINUS SELECT * FROM RPT) x
UNION ALL
SELECT 'DICH - NGUON' AS SRC_FLAG, y.* FROM (SELECT * FROM RPT MINUS SELECT * FROM SRC) y;
) RESULT_CHECK
WHERE RESULT_CHECK.SYSTEMNAME = 'CLOS'
