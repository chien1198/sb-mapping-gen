WITH SRC_BASE AS (
SELECT
	'CLOS' AS SYSTEMNAME,
	A.WINAME AS WINAME,
	B.CUSTOMER_NAME AS CUSTOMER_NAME,
	A.WORKSTEP AS WORKSTEP,
	A.USERNAME AS UND_MAKER,
	(SELECT MIN(E.ENTRYDATE) FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT E
	 WHERE E.WINAME = A.WINAME AND E.WORKSTEP IN ('UnderwriterMaker', 'UnderwriterChecker')) AS ENTRYDATE,
	(SELECT MAX(E.EXITDATE) FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT E
	 WHERE E.WINAME = A.WINAME AND E.WORKSTEP IN ('UnderwriterMaker', 'UnderwriterChecker')) AS EXITDATE,
	CASE
		WHEN EXISTS (SELECT 1 FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT E1
			 WHERE E1.WINAME = A.WINAME
			 AND E1.WORKSTEP IN ('CreditApproval','CreditCommittee')
			 AND E1.DECISION IN ('Send To HOSupport','Reject','Submit','Send To PostSanction'))
			THEN 'Hồ sơ đã chuyển sang bước cấp PD và đã được phê duyệt'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.WFINSTRUMENTTABLE C
			 WHERE C.PROCESSINSTANCEID = A.WINAME
			 AND C.PROCESSNAME = 'CLOS'
			 AND C.ACTIVITYNAME IN ('CreditApproval','CreditCommittee')
			 AND C.CREATEDBY NOT IN ('10000380','10000020','10000420','10000140','10000100'))
			THEN 'Hồ sơ đã chuyển sang bước của cấp phê duyệt nhưng chưa PD'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT E2
			 WHERE E2.WINAME = A.WINAME
			 AND E2.WORKSTEP = 'UnderwriterMaker'
			 AND E2.DECISION = 'Cancel')
			THEN 'Hồ sơ CVTĐ đã xử lý và chốt trạng thái tại bước của CVTĐ'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.WFINSTRUMENTTABLE C1
			 WHERE C1.PROCESSINSTANCEID = A.WINAME
			 AND C1.PROCESSNAME = 'CLOS'
			 AND C1.ACTIVITYNAME = 'UnderwriterMaker'
			 AND C1.CREATEDBY NOT IN ('10000380','10000020','10000420','10000140','10000100'))
			THEN 'Hồ sơ CVTĐ đang/phải xử lý'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT E3
			 WHERE E3.WINAME = A.WINAME
			 AND E3.WORKSTEP = 'UnderwriterMaker'
			 AND E3.DECISION IN ('Send_Back to DDE','Additional_Doc_Required','Send_Back to BranchSupport',
				'Send Back DataInputerChecker','Send To Legal or FI or Phone Verification'))
			THEN 'Hồ sơ CVTĐ đã xử lý nhưng chuyển/trả lại các bộ phận để bổ sung/làm rõ'
		ELSE NULL
	END AS FLAG,
	A.REMARKS AS REMARKS,
	-- REPORT_DATE: UT1 phe duyet cuoi > UT2 Cancel tai UnderwriterMaker > UT3 ngay du lieu
	TRUNC(COALESCE(
		(SELECT MAX(E.EXITDATE) FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT E
		 WHERE E.WINAME = A.WINAME AND E.WORKSTEP IN ('CreditCommittee','CreditApproval')
		 AND E.DECISION IN ('Send To HOSupport','Reject','Submit','Send To PostSanction','Submit To DisbursementMaker')),
		(SELECT MAX(E.EXITDATE) FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT E
		 WHERE E.WINAME = A.WINAME AND E.WORKSTEP = 'UnderwriterMaker' AND E.DECISION = 'Cancel'),
		TO_DATE(:DATE,'YYYYMMDD'))) AS REPORT_DATE
FROM (
	SELECT X.*,
		ROW_NUMBER() OVER (PARTITION BY X.WINAME
			ORDER BY X.ENTRYDATE DESC, X.EXITDATE DESC NULLS FIRST) AS RN
	FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT X
	WHERE X.WORKSTEP = 'UnderwriterMaker'
) A
LEFT JOIN SBLOS2.NG_SB_CLOS_CUST_INFO B ON A.WINAME = B.WI_NAME
WHERE A.RN = 1

UNION ALL

SELECT
	'RLOS' AS SYSTEMNAME,
	A.WINAME AS WINAME,
	B.FULL_NAME AS CUSTOMER_NAME,
	A.WORKSTEP AS WORKSTEP,
	A.USERNAME AS UND_MAKER,
	(SELECT MIN(E.ENTRYDATE) FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT E
	 WHERE E.WINAME = A.WINAME AND E.WORKSTEP IN ('UnderwriterMaker', 'UnderwriterChecker')) AS ENTRYDATE,
	(SELECT MAX(E.EXITDATE) FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT E
	 WHERE E.WINAME = A.WINAME AND E.WORKSTEP IN ('UnderwriterMaker', 'UnderwriterChecker')) AS EXITDATE,
	CASE
		WHEN EXISTS (SELECT 1 FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT E1
			 WHERE E1.WINAME = A.WINAME
			 AND E1.WORKSTEP IN ('CreditApproval','CreditCommittee')
			 AND E1.DECISION IN ('Send To HOSupport','Reject','Submit','Send To PostSanction'))
			THEN 'Hồ sơ đã chuyển sang bước cấp PD và đã được phê duyệt'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.WFINSTRUMENTTABLE C
			 WHERE C.PROCESSINSTANCEID = A.WINAME
			 AND C.PROCESSNAME = 'RLOS'
			 AND C.ACTIVITYNAME IN ('CreditApproval','CreditCommittee')
			 AND C.CREATEDBY NOT IN ('10000380','10000020','10000420','10000140','10000100'))
			THEN 'Hồ sơ đã chuyển sang bước của cấp phê duyệt nhưng chưa PD'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT E2
			 WHERE E2.WINAME = A.WINAME
			 AND E2.WORKSTEP = 'UnderwriterMaker'
			 AND E2.DECISION = 'Cancel')
			THEN 'Hồ sơ CVTĐ đã xử lý và chốt trạng thái tại bước của CVTĐ'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.WFINSTRUMENTTABLE C1
			 WHERE C1.PROCESSINSTANCEID = A.WINAME
			 AND C1.PROCESSNAME = 'RLOS'
			 AND C1.ACTIVITYNAME = 'UnderwriterMaker'
			 AND C1.CREATEDBY NOT IN ('10000380','10000020','10000420','10000140','10000100'))
			OR (A.WORKSTEP = 'UnderwriterMaker'
			 AND A.DECISION = 'Send to UWChecker')
			THEN 'Hồ sơ CVTĐ đang/phải xử lý'
		WHEN EXISTS (SELECT 1 FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT E3
			 WHERE E3.WINAME = A.WINAME
			 AND E3.WORKSTEP = 'UnderwriterMaker'
			 AND E3.DECISION IN ('Legal_Assessment','Additional_Doc_Required','Send_Back',
				'Send_Back to DDE','Send Back DataInputerChecker','Send To Legal or FI or Phone Verification'))
			THEN 'Hồ sơ CVTĐ đã xử lý nhưng chuyển/trả lại các bộ phận để bổ sung/làm rõ'
		ELSE NULL
	END AS FLAG,
	A.REMARKS AS REMARKS,
	TRUNC(COALESCE(
		(SELECT MAX(E.EXITDATE) FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT E
		 WHERE E.WINAME = A.WINAME AND E.WORKSTEP IN ('CreditCommittee','CreditApproval')
		 AND E.DECISION IN ('Send To HOSupport','Reject','Submit','Send To PostSanction','Submit To DisbursementMaker')),
		(SELECT MAX(E.EXITDATE) FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT E
		 WHERE E.WINAME = A.WINAME AND E.WORKSTEP = 'UnderwriterMaker' AND E.DECISION = 'Cancel'),
		TO_DATE(:DATE,'YYYYMMDD'))) AS REPORT_DATE
FROM (
	SELECT X.*,
		ROW_NUMBER() OVER (PARTITION BY X.WINAME
			ORDER BY X.ENTRYDATE DESC, X.EXITDATE DESC NULLS FIRST) AS RN
	FROM SBLOS2.NG_SB_RLOS_ENTRY_EXIT X
	WHERE X.WORKSTEP = 'UnderwriterMaker'
) A
LEFT JOIN SBLOS2.NG_SB_RLOS_APPLICANT_GENERAL B ON A.WINAME = B.WI_NAME
WHERE A.RN = 1
),
SRC AS (
	SELECT
		TO_CHAR(TRUNC(REPORT_DATE,'IW'),'YYYYMMDD') || '-' || TO_CHAR(TRUNC(REPORT_DATE,'IW') + 6,'YYYYMMDD') AS REPORT_WEEK,
		REPORT_DATE, SYSTEMNAME, WINAME, CUSTOMER_NAME, WORKSTEP, UND_MAKER,
		ENTRYDATE, EXITDATE, FLAG, REMARKS
	FROM SRC_BASE
TBL AS (
	SELECT REPORT_WEEK, REPORT_DATE, SYSTEMNAME, WINAME, CUSTOMER_NAME, WORKSTEP, UND_MAKER,
		ENTRYDATE, EXITDATE, FLAG, REMARKS
	FROM PDTD_DTM.BC4
)
SELECT * FROM SRC MINUS SELECT * FROM TBL
