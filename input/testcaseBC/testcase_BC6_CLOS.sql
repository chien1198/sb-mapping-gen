WITH PROCESSED_DATE AS (
SELECT DISTINCT B.WINAME,
	TRUNC(
		CASE
			WHEN EXISTS (
				SELECT 1 FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT B1
				WHERE B1.WINAME = B.WINAME
				AND B1.WORKSTEP IN ('CreditCommittee', 'CreditApproval')
				AND B1.DECISION IN ('Send To HOSupport', 'Reject', 'Submit', 'Send To PostSanction', 'Submit To DisbursementMaker'))
			THEN (
				SELECT MAX(B1.EXITDATE) FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT B1
				WHERE B1.WINAME = B.WINAME
				AND B1.WORKSTEP IN ('CreditCommittee', 'CreditApproval')
				AND B1.DECISION IN ('Send To HOSupport', 'Reject', 'Submit', 'Send To PostSanction', 'Submit To DisbursementMaker'))
			WHEN EXISTS (
				SELECT 1 FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT B2
				WHERE B2.WINAME = B.WINAME AND B2.WORKSTEP = 'CancelRevoke')
			THEN (
				SELECT MAX(NVL(B2.EXITDATE, B2.ENTRYDATE)) FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT B2
				WHERE B2.WINAME = B.WINAME AND B2.WORKSTEP = 'CancelRevoke')
			ELSE (
				SELECT MAX(B3.EXITDATE) FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT B3
				WHERE B3.WINAME = B.WINAME)
		END
	) AS PROCESSED_DATE
FROM SBLOS2.NG_SB_CLOS_ENTRY_EXIT B
),
SRC AS (
SELECT
	A.WI_NAME AS WI_NAME,
	A.DEVIATION_TYPE AS DEVIATION_TYPE,
	A.DEV_PROPOSAL AS DEV_PROPOSAL,
	P.PROCESSED_DATE AS PROCESSED_DATE
FROM SBLOS2.NG_SB_CLOS_CONDITON_CDGRID A
JOIN PROCESSED_DATE P ON A.WI_NAME = P.WINAME
),
TBL AS (
SELECT
	WI_NAME,
	DEVIATION_TYPE,
	DEV_PROPOSAL,
	TRUNC(PROCESSED_DATE) AS PROCESSED_DATE
FROM PDTD_DTM.BC6
)
SELECT 'NGUON - DICH' AS SRC, x.* FROM (SELECT * FROM SRC MINUS SELECT * FROM TGT) x
UNION ALL
SELECT 'DICH - NGUON' AS SRC, y.* FROM (SELECT * FROM TGT MINUS SELECT * FROM SRC) y;